import numpy as np
import os

# Assuming the main modules are in the same directory or accessible in PYTHONPATH
from vbs_parser import VBSConfig
from vbs_field import Field
from vbs_environment import Environment # May not be strictly needed if we mock effectively
from vbs_solver import VisibilityBasedSolver

def load_grid_from_txt(filepath, dtype=float):
    """Loads a 2D grid from a space-separated text file."""
    if not os.path.exists(filepath):
        print(f"Error: Test data file not found: {filepath}")
        print("Please generate this file from the C++ version.")
        return None
    return np.loadtxt(filepath, dtype=dtype)

def load_light_source_from_txt(filepath):
    """Loads light source (x, y) from a text file."""
    if not os.path.exists(filepath):
        print(f"Error: Test data file not found: {filepath}")
        print("Please generate this file from the C++ version.")
        return None
    try:
        coords = np.loadtxt(filepath, dtype=int)
        if coords.shape == (2,):
            return tuple(coords)
        else:
            print(f"Error: Light source file {filepath} does not contain two coordinates.")
            return None
    except Exception as e:
        print(f"Error loading light source from {filepath}: {e}")
        return None

def run_comparison_test():
    print("Running C++ vs Python _compute_visibility comparison test...")

    base_dir = "./cpp_test_data/" # Assume C++ output files are here
    os.makedirs(base_dir, exist_ok=True) # Ensure dir exists for user to put files

    # File paths for C++ generated data
    occ_filepath = os.path.join(base_dir, "cpp_input_occupancy.txt")
    ls_filepath = os.path.join(base_dir, "cpp_input_light_source.txt")
    vis_out_filepath = os.path.join(base_dir, "cpp_output_local_visibility.txt")

    # 1. Load data generated by C++
    cpp_occupancy_data = load_grid_from_txt(occ_filepath)
    cpp_light_source_coords = load_light_source_from_txt(ls_filepath)
    cpp_expected_visibility_data = load_grid_from_txt(vis_out_filepath)

    if cpp_occupancy_data is None or cpp_light_source_coords is None or cpp_expected_visibility_data is None:
        print("One or more C++ data files are missing or failed to load.")
        print(f"Please ensure the following files exist in '{base_dir}':")
        print(f" - {os.path.basename(occ_filepath)} (space-separated occupancy grid, 1=free, 0=obstacle)")
        print(f" - {os.path.basename(ls_filepath)} (two space-separated integers: x y for light source)")
        print(f" - {os.path.basename(vis_out_filepath)} (space-separated visibility grid output from C++)")
        print("Test cannot proceed.")
        # Create dummy files if they don't exist, so the script can run without erroring immediately
        # This helps user understand what's needed.
        if not os.path.exists(occ_filepath): np.savetxt(occ_filepath, np.array([[1,1],[1,0]]), fmt='%.1f')
        if not os.path.exists(ls_filepath): np.savetxt(ls_filepath, np.array([0,0]), fmt='%d')
        if not os.path.exists(vis_out_filepath): np.savetxt(vis_out_filepath, np.array([[1,0.5],[0.5,0]]), fmt='%.3f')
        return False

    ny, nx = cpp_occupancy_data.shape
    cpp_ls_x, cpp_ls_y = cpp_light_source_coords
    # Note: C++ might save (x,y) but Field expects (y,x) for light_pos if it's 0-indexed row,col
    # The txt file for ls_coords should be (x,y) as per instruction.
    # Our Python light_pos is (y,x). So, convert if necessary.
    # However, solver.ls_ is (x,y) matching C++.

    print(f"Loaded C++ data: Grid {ny}x{nx}, Light Source ({cpp_ls_x},{cpp_ls_y})")

    # 2. Setup Python VBS Solver
    # Create a minimal config
    py_config = VBSConfig(
        ncols=nx, nrows=ny,
        light_strength=1.0 # Assuming C++ test used light_strength = 1.0
        # Other config values are not directly used by _compute_visibility
    )

    # Create an Environment (or mock it) to host the Field
    # For _compute_visibility, we primarily need occupancy_complement_ and parameters.
    # We can manually create the Field object.

    py_occupancy_field = Field(nx, ny, 0.0)
    py_occupancy_field.data_ = cpp_occupancy_data # Directly set data

    # Mock environment or set up solver directly
    # Solver initialization needs an env object.
    # Let's create a dummy env for this.
    dummy_env = Environment(py_config) # This will try to generate/load based on mode
    # Override its fields with our loaded data
    dummy_env.nx_ = nx
    dummy_env.ny_ = ny
    dummy_env.shared_visibility_field_ = py_occupancy_field # This is what solver calls occupancy_complement_

    py_solver = VisibilityBasedSolver(dummy_env)

    # Set the light source for the Python solver
    py_solver.ls_ = (cpp_ls_x, cpp_ls_y) # Solver uses (x,y) for ls_

    # Ensure local visibility map is sized correctly (it is by constructor)
    # py_solver.visibility_.resize(nx, ny, 0.0) # Already done in solver init

    # 3. Call Python's _compute_visibility
    print("Running Python _compute_visibility...")
    py_solver._compute_visibility()
    python_generated_visibility_data = py_solver.visibility_.data_

    # 4. Compare results
    print("Comparing Python output with C++ output...")
    try:
        #rtol (relative tolerance) and atol (absolute tolerance) might need tuning
        np.testing.assert_allclose(
            python_generated_visibility_data,
            cpp_expected_visibility_data,
            rtol=1e-5,
            atol=1e-7, # Adjusted atol for typical float comparisons
            err_msg="Mismatch between Python and C++ local visibility maps."
        )
        print("SUCCESS: Python _compute_visibility output matches C++ output within tolerance.")
        return True
    except AssertionError as e:
        print("FAILURE: Outputs do NOT match.")
        print(e)
        # For detailed diff, one might save the python_generated_visibility_data
        # and use a diff tool, or print side-by-side for small arrays.
        diff = np.abs(python_generated_visibility_data - cpp_expected_visibility_data)
        print("Difference map (absolute):\n", diff)
        print("Max difference:", np.max(diff))
        # print("Python output:\n", python_generated_visibility_data)
        # print("C++ expected output:\n", cpp_expected_visibility_data)
        return False

if __name__ == '__main__':
    if not run_comparison_test():
        print("\nTest FAILED. Please check the C++ data files and the Python implementation.")
    else:
        print("\nTest PASSED.")
    print("Reminder: This test expects specific files in ./cpp_test_data/")
    print("  - cpp_input_occupancy.txt (NxM grid, 1=free, 0=obs)")
    print("  - cpp_input_light_source.txt (x y coordinates)")
    print("  - cpp_output_local_visibility.txt (NxM grid from C++ computeVisibility)")
